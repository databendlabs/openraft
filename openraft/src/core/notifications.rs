use std::collections::VecDeque;

use crate::RaftTypeConfig;
use crate::async_runtime::MpscReceiver;
use crate::async_runtime::MpscSender;
use crate::async_runtime::Select3;
use crate::async_runtime::SendError;
use crate::async_runtime::TryRecvError;
use crate::async_runtime::mpsc::PeekableReceiver;
use crate::base::BoxFuture;
use crate::core::local_delivery::LocalDelivery;
use crate::core::notification::Notification;
use crate::type_config::TypeConfigExt;
use crate::type_config::alias::MpscReceiverOf;
use crate::type_config::alias::MpscSenderOf;
use crate::type_config::alias::OneshotReceiverOf;

/// The most notifications one engine command generates for [`RaftCore`] itself.
///
/// `SaveVote` for a pending vote generates `LocalIO`, then a self `VoteResponse`.
///
/// [`RaftCore`]: crate::core::RaftCore
const MAX_LOCAL_BATCH: usize = 2;

/// A send of one self-notification into the shared notification channel.
///
/// It owns a sender clone and the notification, so it borrows neither [`Notifications`] nor the
/// engine. Dropping it before it completes drops the notification.
type LocalSend<C> = BoxFuture<'static, Result<(), SendError<Notification<C>>>>;

/// The notification channel of [`RaftCore`], and the notifications it generates for itself.
///
/// Workers, replication tasks, and timers send into the shared bounded channel through sender
/// clones from [`Self::sender`]. A command that [`RaftCore`] runs must not await that channel:
/// [`RaftCore`] is its only consumer, so a full channel would wait for capacity that only
/// [`RaftCore`] can free. Such a command [`enqueue`](Self::enqueue)s its notifications here
/// instead, and [`RaftCore`] moves them into the channel with [`Self::deliver_local`] after the
/// command returns, handling every notification that call receives.
///
/// [`RaftCore`]: crate::core::RaftCore
pub(crate) struct Notifications<C>
where C: RaftTypeConfig
{
    /// Keeps the channel open while [`RaftCore`](crate::core::RaftCore) runs, and is cloned for
    /// every producer.
    sender: MpscSenderOf<C, Notification<C>>,

    receiver: PeekableReceiver<MpscReceiverOf<C, Notification<C>>, Notification<C>>,

    /// The send of the oldest self-notification, kept until it completes.
    ///
    /// Its notification is logically ahead of every notification in `local`.
    in_flight: Option<LocalSend<C>>,

    /// Self-notifications waiting for `in_flight` to complete, oldest first.
    local: VecDeque<Notification<C>>,
}

impl<C> Notifications<C>
where C: RaftTypeConfig
{
    pub(crate) fn new(sender: MpscSenderOf<C, Notification<C>>, receiver: MpscReceiverOf<C, Notification<C>>) -> Self {
        Self {
            sender,
            receiver: receiver.peekable(),
            in_flight: None,
            local: VecDeque::with_capacity(MAX_LOCAL_BATCH),
        }
    }

    /// Returns a sender for a producer that runs independently of command execution.
    pub(crate) fn sender(&self) -> MpscSenderOf<C, Notification<C>> {
        self.sender.clone()
    }

    /// Buffers a notification generated by the command being run.
    pub(crate) fn enqueue(&mut self, notification: Notification<C>) {
        let buffered = usize::from(self.in_flight.is_some()) + self.local.len();
        debug_assert!(
            buffered < MAX_LOCAL_BATCH,
            "a command generates at most {} self-notifications; buffered: {}, new: {}",
            MAX_LOCAL_BATCH,
            buffered,
            notification
        );
        self.local.push_back(notification);
    }

    /// Returns whether any self-notification has not entered the channel yet.
    pub(crate) fn has_buffered(&self) -> bool {
        self.in_flight.is_some() || !self.local.is_empty()
    }

    /// Moves buffered self-notifications into the channel, oldest first, while receiving.
    ///
    /// It returns [`LocalDelivery::Delivered`] once all of them are in the channel, and
    /// [`LocalDelivery::Received`] when a notification arrives while a send waits for capacity.
    /// Since the caller is the only consumer, receiving is what frees capacity for that send. The
    /// pending send is kept, so the caller handles the notification and calls again.
    ///
    /// Each selection polls `rx_shutdown`, then the pending send, then the receiver. A ready send
    /// thus wins over a ready notification, and incoming notifications cannot starve it.
    pub(crate) async fn deliver_local(&mut self, rx_shutdown: &mut OneshotReceiverOf<C, ()>) -> LocalDelivery<C> {
        loop {
            if self.in_flight.is_none() {
                let Some(notification) = self.local.pop_front() else {
                    return LocalDelivery::Delivered;
                };

                let sender = self.sender.clone();
                let send = async move { sender.send(notification).await };
                self.in_flight = Some(Box::pin(send));
            }

            // Safe unwrap: `in_flight` is set above.
            let send = self.in_flight.as_mut().unwrap();

            let selected = C::select3(&mut *rx_shutdown, send.as_mut(), self.receiver.recv()).await;
            match selected {
                Select3::First(_) => return LocalDelivery::Shutdown,
                Select3::Second(Ok(())) => self.in_flight = None,
                Select3::Second(Err(_)) => return LocalDelivery::Closed,
                Select3::Third(Some(notification)) => return LocalDelivery::Received(notification),
                Select3::Third(None) => return LocalDelivery::Closed,
            }
        }
    }

    pub(crate) fn try_recv(&mut self) -> Result<Notification<C>, TryRecvError> {
        self.receiver.try_recv()
    }

    pub(crate) async fn recv(&mut self) -> Option<Notification<C>> {
        self.receiver.recv().await
    }

    /// Inspects the next notification in the channel without consuming it or waiting.
    pub(crate) fn peek(&mut self) -> Result<&Notification<C>, TryRecvError> {
        self.receiver.peek()
    }
}

